import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const repo = join(here, "../../..");
const shapes = ["non", "chung", "aodai", "ran", "sen"];
const currentDir = join(repo, "packages/ui-web/src/vnbot-avatars");
const approved = {
  non: "d0684b5ae8256011dde7a60e881e84ce727b00b2eac73c2d8bd136754613e46f",
  chung: "29e5a6c51f9a836311d1e96256896d2a96994ab63a3dc9c82dc847eebc224000",
  aodai: "19993a9241504c68e2bea0c64ee7503c34f2d2bcc080360ed9da133259b4f7ec",
  ran: "527278cc0f1957aab86c0379dc3200643d4ad971ef399efa52daf52639f6ab32",
  sen: "737bd46a9beeeed39017c96dd177fd7ce5d00bf882678fc4b9dc61923bea366b",
};
const artFile = join(repo, "packages/core/src/vnbot-avatar-art.ts");

function readShape(dir, shape) {
  return readFileSync(join(dir, `${shape}.svg`));
}

function fail(message) {
  console.error(message);
  process.exit(1);
}

const current = new Map();
for (const shape of shapes) {
  const bytes = readShape(currentDir, shape);
  const hash = createHash("sha256").update(bytes).digest("hex");
  if (hash !== approved[shape]) fail(`${shape}.svg differs from approved VNBot artwork`);
  current.set(shape, bytes.toString("utf8"));
}

const write = process.argv.includes("--write");
if (write) {
  const entries = shapes
    .map((shape) => `  ${shape}: ${JSON.stringify(current.get(shape))},`)
    .join("\n");
  const source = `// Generated by packages/core/scripts/vnbot-avatar-art.mjs from packages/ui-web/src/vnbot-avatars.
// The script refuses to write unless those files match the reviewed artwork hashes.

export const VNBOT_SHAPES = ["non", "chung", "aodai", "ran", "sen"] as const;

export type VnbotShape = (typeof VNBOT_SHAPES)[number];

export const VNBOT_AVATAR_SVG: Record<VnbotShape, string> = {
${entries}
};
`;
  writeFileSync(artFile, source);
  console.log(`wrote ${artFile}`);
}

const art = await import(pathToFileURL(artFile).href);
for (const shape of shapes) {
  const svg = current.get(shape);
  if (art.VNBOT_AVATAR_SVG[shape] !== svg) {
    fail(`${artFile} ${shape} is not the approved SVG`);
  }
  console.log(`${shape} ${createHash("sha256").update(svg).digest("hex")} matches old VNBot`);
}
console.log("vnbot avatar artwork check passed");
